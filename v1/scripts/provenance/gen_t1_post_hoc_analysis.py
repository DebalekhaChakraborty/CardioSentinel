for s in GROUP_B:
    f, e, c = folds[s], folds[s]["episode_evidence"], folds[s]["primary_confusion"]
    w(f"| `{s}` | {f['fold_index']} | **{e['reference_episodes']}** | {e['predicted_event_runs']} "
      f"| {e['matched_episodes']} | {c['false_negative']:,} | {c['true_positive']} "
      f"| {subs[s]['episode_f1']:.4f} |")
w()
b_ref = sum(folds[s]["episode_evidence"]["reference_episodes"] for s in GROUP_B)
b_fn = sum(folds[s]["primary_confusion"]["false_negative"] for s in GROUP_B)
w("> **Post-hoc descriptive analysis.** Summing the published counts: these four")
w(f"> subjects carry **{b_ref} reference episodes**, of which **0 were matched**, and")
w(f"> **{b_fn:,} false-negative windows**. No rate, ratio or normalised quantity is")
w("> derived from these sums.")
w()
w("**Interpretation.** For Group B the measurement is one of *complete detection")
w("failure on subjects that had annotated episodes*. Three of the four produced no")
w("predicted event run at all; `ltstdb:s3072` produced one run that did not overlap")
w("its single reference episode, so it is a matching failure rather than a silence.")
