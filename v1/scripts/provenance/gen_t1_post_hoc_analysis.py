w("## 2. Latency interpretation")
w()
w("The descriptive report §6 and §9.2 report onset latency. This section fixes how")
w("it may be described.")
w()
w("**Definition.** `_onset_latency` computes")
w()
w("```")
w("(start_samples[run_begin] - start_samples[episode_begin]) / 250.0")
w("```")
w()
w("seconds from a matched episode's annotated onset to its matched run's onset. It")
w("is a **signed offset**, not a delay. Negative values indicate the matched")
w("predicted run started **before** the annotated episode onset.")
w()
w("**Why a negative offset does not establish anticipation.**")
w("`match_runs_to_episodes` pairs a run to an episode on **overlap alone** —")
w("`run_begin < end and begin < run_end` — with **no tolerance window** and no")
w("bound on how early a run may begin. A negative offset is therefore equally")
w("consistent with:")
w()
w("- a **persistent `EVENT` state** that was already active and merely overlaps the")
w("  annotated episode, and")
w("- a **long-duration detected run** that spans the annotated onset.")
w()
w("The artifacts record `onset_latency_seconds` but **not run durations**, so this")
w("evidence cannot separate those from genuine anticipation.")
w()
w("**Prohibited terminology.** The following must not be used of any T1 latency")
w("figure, in this repository or in any manuscript drawn from it:")
w()
w("| ❌ Prohibited | Why |")
w("|---|---|")
w("| \"early detection\" | Asserts anticipation the overlap matcher cannot establish |")
w("| \"warning time\" | Implies a clinically actionable interval before onset |")
w("| \"predictive lead time\" | Implies a validated prediction horizon |")
w()
w("**Acceptable phrasing:** *\"signed onset offset\"*, *\"median latency across")
w("detected episodes\"*, or *\"episode-level onset latency distribution among")
w("detected episodes\"*, each stating the sign convention.")
w()
