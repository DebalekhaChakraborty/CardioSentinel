GROUP_B = ["ltstdb:s2019", "ltstdb:s2058", "ltstdb:s2059", "ltstdb:s3072"]

o, w = [], None
o_append = o.append
def w(line=""): o_append(line)

w("# T1 Post-hoc Failure Mode Analysis and Interpretation, V1")
w()
w("**POST-HOC ANALYSIS. This document was written after the measured values were")
w("read.** It is not part of the pre-registration in")
w("`docs/T1_EVIDENCE_ANALYSIS_PLAN_V1.md` and it carries none of that document's")
w("authority. Every quantity here that is not already published in")
w("`docs/T1_DESCRIPTIVE_REPORT_V1.md` is labelled **post-hoc descriptive")
w("analysis** at the point it appears.")
w()
w("## What this document does not do")
w()
w("| | |")
w("|---|---|")
w("| Changes the primary endpoint | **No.** The registered primary remains the subject-macro mean `episode_f1` |")
w("| Changes the primary value | **No.** `episode_f1 = 0.2524` is unchanged and is not recomputed anywhere in this document |")
w("| Removes any subject | **No.** All twelve subjects remain in the registered estimate, including the three with no reference episodes |")
w("| Presents a new headline number | **No.** No alternative performance figure is computed, reported, or implied |")
w("| Recomputes any metric | **No.** Only counts already published in the descriptive report are quoted |")
w("| Alters any promoted artifact | **No.** All seven artifact digests re-verify unchanged |")
w()
w("The registered result stands exactly as reported:")
w()
w("```")
w("Subject-macro mean episode_f1 = 0.2524")
w("95% subject-bootstrap interval = [0.0826, 0.4415]")
w("```")
w()
w("This analysis explains **what the zeros inside that mean are made of**. It does")
w("not adjust the mean, and a reader who wants a single number should continue to")
w("use the registered one.")
w()
w("---")
w()
w("## 1. The seven zero-`episode_f1` subjects are two different failure modes")
w()
w("Seven of twelve subjects score `episode_f1 = 0.0000`. The descriptive report")
w("§9.1 records that these zeros arise for two incomparable reasons. This section")
w("separates them.")
w()
w("`_episode_f1` returns `2 · matched / (predicted_event_runs + reference_episodes)`")
w("and returns undefined **only** when that denominator is zero. A subject with no")
w("reference episodes but at least one predicted run therefore has a non-zero")
w("denominator, zero matches, and a defined score of exactly `0.0`.")
w()
w("### 1.1 Group A — episode-free subjects carrying a false-alarm burden")
w()
w("These subjects have **no annotated ischemic episodes at all**. Their zero is a")
w("false-alarm penalty, not a failure to detect: there was nothing available to")
w("detect.")
w()
w("| Subject | Fold | Reference episodes | Predicted runs | Unmatched predicted runs | FP windows | TP | FN | `episode_f1` |")
w("|---|---|---|---|---|---|---|---|---|")
for s in GROUP_A:
    f, e, c = folds[s], folds[s]["episode_evidence"], folds[s]["primary_confusion"]
    w(f"| `{s}` | {f['fold_index']} | **{e['reference_episodes']}** | {e['predicted_event_runs']} "
      f"| {e['unmatched_predicted_runs']} | {c['false_positive']:,} | {c['true_positive']} "
      f"| {c['false_negative']} | {subs[s]['episode_f1']:.4f} |")
w()
a_runs = sum(folds[s]["episode_evidence"]["predicted_event_runs"] for s in GROUP_A)
a_fp = sum(folds[s]["primary_confusion"]["false_positive"] for s in GROUP_A)
w("> **Post-hoc descriptive analysis.** Summing the published counts: these three")
w(f"> subjects contribute **{a_runs} predicted event runs** and **{a_fp:,} false-positive")
w("> windows** against **0 reference episodes**. No rate, ratio or normalised")
w("> quantity is derived from these sums.")
w()
w("**Interpretation.** For Group A the measurement is one of *false-alarm burden on")
w("subjects without annotated episodes*. `primary_window_mcc` is undefined for all")
w("three because the reference-positive margin is empty, and")
w("`onset_latency_seconds_median` is undefined because no episode existed to match.")
w("Both undefined values are reported as undefined in the descriptive report and")
w("are not filled here.")
w()
w("### 1.2 Group B — reference episodes present, no matched detection")
w()
w("These subjects **do** have annotated episodes. Their zero is a genuine detection")
w("failure.")
w()
w("| Subject | Fold | Reference episodes | Predicted runs | Matched | FN windows | TP | `episode_f1` |")
